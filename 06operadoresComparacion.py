a = 10
b = 5

print("Operadores de comparación:")
print( a == b) # Igualdad
print( a != b) # Desigualdad
print( a > b) # Mayor que
print( a < b) # Menor que
print( a >= b) # Mayor o igual que
print( a <= b) # Menor o igual que

edad = 18
estudiante = True

print("Operadores lógicos:")
print(edad >= 18 and estudiante) # AND lógico
print(edad > 30 or estudiante) # OR lógico
print(not estudiante) # NOT lógico